// Generates shared/abi.ts (typed `as const` ABIs for viem) from Foundry artifacts.
// Usage: forge build && node scripts/export-abis.mjs
import fs from "node:fs";

const contracts = [
  ["dimeAbi", "DimeProtocol.sol/DimeProtocol.json"],
  ["priceVerifierAbi", "OperatorPriceVerifier.sol/OperatorPriceVerifier.json"],
  ["testUsdcAbi", "TestUSDC.sol/TestUSDC.json"],
  ["dimeRightsAbi", "DimeRights.sol/DimeRights.json"],
  ["dimeTokenAbi", "DimeToken.sol/DimeToken.json"],
];
let out = "// GENERATED by scripts/export-abis.mjs from contracts/out — do not edit.\n\n";
for (const [name, path] of contracts) {
  const art = JSON.parse(fs.readFileSync(`contracts/out/${path}`, "utf8"));
  out += `export const ${name} = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
fs.writeFileSync("shared/abi.ts", out);
fs.mkdirSync("envio/abis", { recursive: true });
const dime = JSON.parse(fs.readFileSync("contracts/out/DimeProtocol.sol/DimeProtocol.json", "utf8"));
const rights = JSON.parse(fs.readFileSync("contracts/out/DimeRights.sol/DimeRights.json", "utf8"));
// Envio indexes the protocol address; library events are emitted from it (delegatecall).
const events = [...dime.abi.filter((x) => x.type === "event"), ...rights.abi.filter((x) => x.type === "event")];
const seen = new Set();
fs.writeFileSync("envio/abis/DimeProtocol.json", JSON.stringify(events.filter((e) => !seen.has(e.name) && seen.add(e.name)), null, 2));
console.log("wrote shared/abi.ts and envio/abis/DimeProtocol.json");
