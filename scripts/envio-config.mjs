// Generates envio/config.yaml from a deployment manifest so the indexer never points at a
// hand-typed address. Usage: node scripts/envio-config.mjs deployments/<chainId>.json [rpcUrl]
import fs from "node:fs";
const [manifestPath, rpc] = process.argv.slice(2);
if (!manifestPath) throw new Error("usage: envio-config.mjs <manifest> [rpcUrl]");
const m = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const hypersync = m.chainId === 143 || m.chainId === 10143;
const ev = (s) => `      - event: "${s}"`;
const yaml = `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# GENERATED by scripts/envio-config.mjs from ${manifestPath} — do not edit by hand.
name: dime-indexer
description: DIME protocol activity (${m.stage}, chain ${m.chainId})
handlers: ./src/handlers.ts
field_selection:
  transaction_fields:
    - hash
contracts:
  - name: DimeProtocol
    events:
${[
  "Deposited(address indexed user, uint256 amount, uint256 depositedTotal)",
  "Withdrawn(address indexed user, uint256 amount)",
  "IntentCancelled(address indexed user, uint256 nonce)",
  "PositionOpened(bytes32 indexed id, address indexed user, uint8 route, uint8 side, uint256 collateral, uint16 leverage, uint256 entryPrice, uint256 liquidationPrice, uint256 houseReservation, bytes32 pairId, uint32 configVersion)",
  "PositionSettled(bytes32 indexed id, address indexed user, uint8 route, uint256 exitPrice, int256 grossPnl, uint256 fee, int256 netPnl, uint256 returned, uint8 reason)",
  "HouseReservationChanged(bytes32 indexed id, uint256 newReservation)",
  "ReserveFunded(address indexed from, uint256 amount)",
  "ReserveWithdrawn(address indexed to, uint256 amount)",
  "ProtocolStateChanged(uint8 state)",
  "DimeIssued(address indexed user, uint256 amount, uint64 activationEpoch, int256 cumulativeNetLoss, int256 highWater, uint256 rateE18)",
  "Staked(address indexed user, uint256 amount, uint64 activationEpoch)",
  "Unstaked(address indexed user, uint256 amount)",
  "EpochFunded(uint64 indexed epoch, uint256 eligibleNewEarnings, uint256 target, uint256 funded, uint8 limitedBy)",
  "EpochAdvanced(uint64 indexed epoch, uint256 totalActive)",
  "Claimed(address indexed user, uint256 amount)",
].map(ev).join("\n")}
chains:
  - id: ${m.chainId}
    start_block: ${m.deploymentBlock}
${hypersync ? "" : `    rpc: ${rpc ?? "http://127.0.0.1:8545"}\n`}    contracts:
      - name: DimeProtocol
        address: "${m.protocol}"
`;
fs.writeFileSync("envio/config.yaml", yaml);
console.log(`wrote envio/config.yaml for chain ${m.chainId} @ ${m.protocol} from block ${m.deploymentBlock}${hypersync ? " (HyperSync: requires ENVIO_API_TOKEN)" : " (RPC)"}`);
